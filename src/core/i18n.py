def _normalize_locale_name(value: str | None) -> str:
    if not isinstance(value, str):
        return ""
    return value.strip().replace("_", "-").casefold()


def detect_system_language() -> str:
    candidates = [
        locale.getlocale()[0],
        locale.getdefaultlocale()[0],
        os.environ.get("LC_ALL"),
        os.environ.get("LC_MESSAGES"),
        os.environ.get("LANG"),
    ]
    for candidate in candidates:
        normalized = _normalize_locale_name(candidate)
        if normalized.startswith("zh"):
            return LANGUAGE_ZH_HANS
    return LANGUAGE_EN


def normalize_language(value: object) -> str:
    if isinstance(value, str):
        normalized = value.strip()
        if normalized in SUPPORTED_LANGUAGES:
            return normalized
    return detect_system_language()


def current_language() -> str:
    try:
        from ..settings.storage import current_settings

        return normalize_language(current_settings().language)
    except Exception:
        return detect_system_language()


@dataclass(frozen=True, slots=True)
class Translator:
    language: str

    def t(self, key: str, **kwargs) -> str:
        lang = normalize_language(self.language)
        table = _TRANSLATIONS.get(lang, _TRANSLATIONS[LANGUAGE_EN])
        fallback = _TRANSLATIONS[LANGUAGE_EN]
        template = table.get(key, fallback.get(key, key))
        return template.format(**kwargs) if kwargs else template


def translator(language: str | None = None) -> Translator:
    return Translator(normalize_language(language) if language is not None else current_language())


def t(key: str, **kwargs) -> str:
    return translator().t(key, **kwargs)


def language_display_name(language: str, display_language: str | None = None) -> str:
    display = normalize_language(display_language) if display_language is not None else current_language()
    mapping = {
        LANGUAGE_EN: {
            LANGUAGE_EN: "English",
            LANGUAGE_ZH_HANS: "Chinese (Simplified)",
        },
        LANGUAGE_ZH_HANS: {
            LANGUAGE_EN: "English",
            LANGUAGE_ZH_HANS: "简体中文",
        },
    }
    return mapping.get(display, mapping[LANGUAGE_EN]).get(language, language)


